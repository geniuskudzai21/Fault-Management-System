import { neon, types, type NeonQueryFunction } from '@neondatabase/serverless';

const PG_INT8_OID = 20;
const PG_FOREIGN_KEY_VIOLATION = '23503';
const PG_UNIQUE_VIOLATION = '23505';

types.setTypeParser(PG_INT8_OID, (value: string) => Number(value));

const toPgPlaceholders = (sql: string): string => {
  let out = '';
  let index = 0;
  let i = 0;

  while (i < sql.length) {
    const char = sql[i];

    if (char === "'") {
      out += char;
      i += 1;
      while (i < sql.length) {
        out += sql[i];
        if (sql[i] === "'") {
          if (sql[i + 1] === "'") {
            out += sql[i + 1];
            i += 2;
            continue;
          }
          i += 1;
          break;
        }
        i += 1;
      }
      continue;
    }

    if (char === '-' && sql[i + 1] === '-') {
      const lineEnd = sql.indexOf('\n', i);
      const stop = lineEnd === -1 ? sql.length : lineEnd;
      out += sql.slice(i, stop);
      i = stop;
      continue;
    }

    if (char === '?') {
      index += 1;
      out += `$${index}`;
      i += 1;
      continue;
    }

    out += char;
    i += 1;
  }

  return out;
};

const splitStatements = (sql: string): string[] =>
  sql
    .split(';')
    .map((statement) => statement.trim())
    .filter((statement) => statement.length > 0);

export interface RunResult {
  rowCount: number;
}

export interface Database {
  get<T = any>(query: string, params?: unknown[]): Promise<T | undefined>;
  all<T = any>(query: string, params?: unknown[]): Promise<T[]>;
  run(query: string, params?: unknown[]): Promise<RunResult>;
  exec(sql: string): Promise<void>;
  close(): Promise<void>;
}

