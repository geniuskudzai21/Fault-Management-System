export const ensureSchema = async (): Promise<Database> => {
  const connectionString = process.env.DATABASE_URL;
  if (!connectionString) {
    throw new Error('DATABASE_URL is not set. Add your Neon connection string to the environment.');
  }

  client = neon(connectionString, { fullResults: true });

  db = {
    get: async <T = any>(query: string, params: unknown[] = []): Promise<T | undefined> => {
      const result = await client!.query(toPgPlaceholders(query), params as any[]);
      return result.rows[0] as T | undefined;
    },
    all: async <T = any>(query: string, params: unknown[] = []): Promise<T[]> => {
      const result = await client!.query(toPgPlaceholders(query), params as any[]);
      return result.rows as T[];
    },
    run: async (query: string, params: unknown[] = []): Promise<RunResult> => {
      const result = await client!.query(toPgPlaceholders(query), params as any[]);
      return { rowCount: result.rowCount ?? 0 };
    },
    exec: async (sql: string): Promise<void> => {
      for (const statement of splitStatements(sql)) {
        await client!.query(statement);
      }
    },
    close: async (): Promise<void> => {
      client = undefined;
      db = undefined;
    },
  };

  await db.exec(SCHEMA);

  return db;
};

export const initDb = async (): Promise<Database> => {
  const db = await ensureSchema();

  const bcrypt = await import('bcryptjs');
  const admin = await db.get('SELECT id FROM users WHERE email = ?', ['admin@zesa.co.zw']);
  if (!admin) {
    const hashedPassword = await bcrypt.hash('admin123', 10);
    await db.run(
      'INSERT INTO users (name, email, password, role, area, status) VALUES (?, ?, ?, ?, ?, ?)',
      ['System Admin', 'admin@zesa.co.zw', hashedPassword, 'Admin', 'Avenues', 'active']
    );
    console.log('Default admin user created: admin@zesa.co.zw / admin123');
  }

  return db;
};

export const getDb = (): Database | undefined => db;

export const isForeignKeyViolation = (error: unknown): boolean =>
  Boolean(error) && (error as { code?: string }).code === PG_FOREIGN_KEY_VIOLATION;

export const isUniqueViolation = (error: unknown): boolean =>
  Boolean(error) && (error as { code?: string }).code === PG_UNIQUE_VIOLATION;
